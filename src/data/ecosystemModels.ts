interface CompactModelSpec {
  id: string;
  name: string;
  shortName: string;
  codename: string;
  provider: string;
  labId: LabId;
  labColor: string;
  specialtyWing: Exclude<SpecialtyWingId, 'all'>;
  license: LicenseType;
  launchedLabel: string;
  zone: ZoneId;
  title: string;
  badge?: string;
  feeTier: FeeTier;
  costPerTaskUsd: number;
  aaIndex: number;
  firstTokenSec: number;
  contextWindow: string;
  traits: CandidateTraits;
  modalities: Omit<CandidateModalities, 'text'>;
  bestFor: string[];
  avoidFor: string[];
  codingScore: string;
  multimodalScore: string;
  gpqaScore: string;
  verifiedBenchmarkIds: BenchmarkSourceId[];
  watchOutFor: string;
  speechBubble: string;
  appearance: CandidateAppearance;
  overtimeReply: string;
  leaseReply: string;
}

const SENIORITY_MAP: Record<ZoneId, { seniority: Seniority; label: string }> = {
  corner_office: { seniority: 'principal', label: 'Corner-Office Principal' },
  mid_level: { seniority: 'specialist', label: 'Mid-Level Specialist' },
  front_desk: { seniority: 'associate', label: 'Front-Desk Associate' },
};

function makeModel(spec: CompactModelSpec, index: number): Candidate {
  const sen = SENIORITY_MAP[spec.zone];
  return {
    id: spec.id,
    name: spec.name,
    shortName: spec.shortName,
    codename: spec.codename,
    provider: spec.provider,
    labId: spec.labId,
    labColor: spec.labColor,
    specialtyWing: spec.specialtyWing,
    license: spec.license,
    isFlagship: false,
    launchedLabel: spec.launchedLabel,
    zone: spec.zone,
    seniority: sen.seniority,
    seniorityLabel: sen.label,
    title: spec.title,
    badge: spec.badge,
    feeTier: spec.feeTier,
    costPerTaskUsd: spec.costPerTaskUsd,
    aaIndex: spec.aaIndex,
    firstTokenSec: spec.firstTokenSec,
    contextWindow: spec.contextWindow,
    traits: spec.traits,
    modalities: { text: true, ...spec.modalities },
    bestFor: spec.bestFor,
    avoidFor: spec.avoidFor,
    benchmarkScores: {
      aaIndex: spec.aaIndex,
      codingScore: spec.codingScore,
      multimodalScore: spec.multimodalScore,
      gpqaScore: spec.gpqaScore,
    },
    verifiedBenchmarkIds: spec.verifiedBenchmarkIds,
    watchOutFor: spec.watchOutFor,
    speechBubble: spec.speechBubble,
    appearance: spec.appearance,
    deskSlot: index % 8,
    trialShifts: {
      sunday_overtime: {
        approachTag: `${spec.provider} · ${spec.codename}`,
        response: spec.overtimeReply,
        editorialNote: `${spec.shortName} mirrors ${spec.provider}'s house voice—great for ${spec.bestFor[0].toLowerCase()}.`,
      },
      lease_clause: {
        approachTag: `${spec.feeTier} · ${spec.license === 'open_weight' ? 'Open-Weight' : 'API'}`,
        response: spec.leaseReply,
        editorialNote: `${spec.watchOutFor}`,
      },
    },
  };
}

